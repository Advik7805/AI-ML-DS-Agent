"""The committed samples in ``samples/``, checked against the bodies that accept them.

A sample is a promise. The studio tells a first-time visitor "drop your own file", and
``samples/`` is the answer to "with what file?" — so a sample that a body *rejects* is worse
than no sample at all: it tells the visitor the product is broken when the file is what is
wrong. These tests are the promise, restated as assertions:

- every file is accepted by its body, with columns actually matched to the model;
- the README lists every file, because a sample nobody can find is not a sample;
- nothing is big enough to hit the upload cap before the body's own validation does;
- the churn sample carries its label (so the upload reports real held-out metrics, not just a
  score distribution), and the FD001 sample stays the real 26-column layout (so the padding path
  keeps being demonstrated by the thing that claims to demonstrate it).

``python scripts/make_samples.py --verify`` is the same check by hand, printing one line per file.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from core.sessions import MAX_FILE_BYTES, Session
from scripts.make_samples import SAMPLES_LIST

SAMPLES = Path(__file__).resolve().parents[1] / "samples"
README = SAMPLES / "README.md"

#: The one sample that is a *document*: it has no columns to match, and its upload path indexes
#: chunks instead of scoring rows. Asserting "columns matched" for it would be asserting the
#: wrong contract, which is what the skip below is about.
DOCUMENT_MODULE = "rag"

#: The sample that must stay 26 columns wide (unit, cycle, three settings, 21 sensors) even
#: though this repo's own schema carries six settings — the real NASA FD001 layout is what the
#: maintenance body promises to accept, and the padding is reported in the analysis notes.
FD001_SAMPLE = "maintenance/train_FD001_sample.txt"


@pytest.mark.parametrize("sample", SAMPLES_LIST, ids=lambda s: s.relative.replace("/", "::"))
def test_every_sample_is_accepted_by_its_body(registry, sample) -> None:
    """The whole point: drop the file, get a result, get no refusal."""
    path = SAMPLES / sample.relative
    assert path.exists(), f"{sample.relative} is missing — run scripts/make_samples.py"

    body = registry.get(sample.module_id)
    # A fresh session per upload, exactly as the API builds one per request: an upload is
    # in-memory and session-scoped, never persisted and never merged into the shipped corpus.
    result = body.analyze_upload(path.name, path.read_bytes(), Session(id="s_samples"))

    assert result.module_id == sample.module_id
    assert result.rows, f"{sample.relative} produced no rows or chunks"

    if sample.module_id != DOCUMENT_MODULE:
        matched = result.columns_report.matched
        assert matched, (
            f"{sample.relative} matched none of {body.id}'s columns. The sample is generated by "
            f"this body's own loader or generator, so this means the schema drifted, not the file."
        )

    if sample.relative == FD001_SAMPLE:
        assert any("filled with the value" in note for note in result.notes), (
            "the FD001 sample must stay the real 26-column layout; with all six settings present "
            "the upload path stops demonstrating the padding it documents"
        )


def test_the_readme_lists_every_sample() -> None:
    """A sample nobody can find is not a sample."""
    text = README.read_text()
    for sample in SAMPLES_LIST:
        assert sample.relative in text, f"{sample.relative} is not listed in samples/README.md"


def test_no_sample_is_large_enough_to_be_rejected_for_size() -> None:
    """The cap is 10 MB, but a sample above 2 MB is a sample nobody downloads from Git."""
    for sample in SAMPLES_LIST:
        size = (SAMPLES / sample.relative).stat().st_size
        assert 0 < size <= 2 * 1024 * 1024, f"{sample.relative} is {size:,} bytes"
        assert size < MAX_FILE_BYTES


def test_the_churn_sample_carries_its_label() -> None:
    """Labelled uploads are the interesting case: real precision/recall instead of a histogram."""
    import pandas as pd

    df = pd.read_csv(SAMPLES / "churn/customers.csv")
    assert "churn" in df.columns
    assert set(df["churn"].unique()) <= {0, 1}, "the label must stay binary, as the body's is"
    assert 0 < df["churn"].mean() < 1, "one class only would make the metrics undefined"
